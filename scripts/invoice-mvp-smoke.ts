/** Reproducible deployed-Convex smoke; requires an explicitly initialized EMPTY synthetic run. */
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { createServiceFromEnv } from "../src/invoice-mvp/service";
import { demoBatch } from "../src/invoice-mvp/demo";

const service = createServiceFromEnv();
assert.equal(service.mode, "deterministic", "This free smoke must never invoke a model");
assert.equal((await service.workspace()).cases.length, 0, "Use a freshly initialized empty synthetic run; existing work is never reset");
const commands: string[] = [];
await service.ingestBatch(demoBatch());
commands.push("import initial public demo");
let processed = await service.processPending({ maxCases: 100 });
assert.deepEqual(processed.errors, []);
let workspace = await service.workspace();
assert.deepEqual(workspace.customerTotals.map((c) => [c.customerId, c.netCents]), [["demo-acorn", 87500], ["demo-birch", 40000]]);
assert.equal(workspace.progress.duplicate, 1);
assert.equal(workspace.progress.needsReview, 1);
assert.equal(workspace.progress.evidenceMissing, 1);
commands.push("check routine invoice/credit totals and duplicate");
const pending = workspace.cases.find((c) => c.externalId === "demo-ambiguous")!;
const staleDecision = { caseId: pending.caseId, proposalId: pending.currentProposalId!, evidenceVersion: pending.evidenceVersion, idempotencyKey: "smoke-stale", action: "accept" as const };
await service.ingestBatch(demoBatch("late"));
processed = await createServiceFromEnv().processPending({ maxCases: 100 });
assert.deepEqual(processed.errors, []);
await assert.rejects(service.decide(staleDecision), (e: unknown) => typeof e === "object" && e !== null && "code" in e && e.code === "stale_proposal");
commands.push("late revision invalidates prior approval and resumes after service recreation");
workspace = await service.workspace();
const current = workspace.cases.find((c) => c.externalId === "demo-ambiguous")!;
const decision = { caseId: current.caseId, proposalId: current.currentProposalId!, evidenceVersion: current.evidenceVersion, idempotencyKey: "smoke-accept-replay", action: "accept" as const };
const accepted = await service.decide(decision);
const replay = await createServiceFromEnv().decide(decision);
assert.equal(accepted.decisionId, replay.decisionId);
workspace = await service.workspace();
assert.deepEqual(workspace.customerTotals.map((c) => [c.customerId, c.netCents]), [["demo-acorn", 107500], ["demo-birch", 45000]]);
assert.equal(workspace.progress.superseded, 1);
assert.equal(workspace.progress.evidenceMissing, 1);
assert.equal(workspace.progress.pending, 0);
assert.equal(workspace.customerTotals.flatMap((c) => c.contributions).length, 4);
assert.ok(workspace.customerTotals.flatMap((c) => c.contributions).every((c) => c.evidence.length));
commands.push("accept exact current proposal, replay decision, verify one contribution per document");
const revision = workspace.cases.find((c) => c.externalId === "demo-revision" && c.status === "recorded")!;
assert.equal((await service.caseDetail(revision.caseId)).sourceVersions.length, 2);
console.log(JSON.stringify({ result: "PASS", sourceCommit: execFileSync("git", ["rev-parse", "HEAD"], { encoding: "utf8" }).trim(), runId: workspace.runId, backend: "deployed Convex", mode: service.mode, modelCalls: 0, liveEvaluation: "NOT RUN", commands, progress: workspace.progress, customerTotals: workspace.customerTotals.map(({ customerId, grossCents, creditCents, netCents }) => ({ customerId, grossCents, creditCents, netCents })) }, null, 2));
