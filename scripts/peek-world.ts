import { generateWorld } from "../src/world/generate";
const w = generateWorld({ seed: 7, storeCount: Number(process.argv[2] ?? 3), start: "2026-01-01", days: Number(process.argv[3] ?? 14), plantErrors: true });
const byType: Record<string, number> = {};
for (const e of w.events) byType[e.type] = (byType[e.type] ?? 0) + 1;
console.log("events", w.events.length, byType);
console.log("errors", w.answerKey.errors.map((e) => `${e.type}:${e.subject.ref}:${e.amountAtRiskCents}`));
console.log("decoys", w.answerKey.decoys.map((d) => `${d.type}:${d.subject.ref}`));
console.log("truth", w.truth);
const sample = w.events.filter((e) => e.type === "document.received").slice(0, 3);
for (const s of sample) console.log("----\n" + (s.payload.text as string));
const pipe = w.events.find((e) => e.type === "document.received" && String(e.payload.text).startsWith("H|"));
console.log("---- pipe\n" + (pipe?.payload.text as string));
